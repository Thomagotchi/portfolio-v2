// DA tokens.json (DTCG, tolerant of plain values) → dist/tokens.css + dist/tokens.json.
// Groups: color, semantic.{dark,light}, radius, motion, layout → CSS vars. font/fontWeight → tokens.json (Astro Fonts API).
// mark → tokens.json (polygons for the Mark component). Skipped: contrast (DA docs, not tokens).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('./tokens.json', import.meta.url), 'utf8'));
const SKIP = new Set(['contrast', 'mark', 'font', 'fontWeight', 'semantic']);
const val = (t) => (t && typeof t === 'object' && '$value' in t ? t.$value : t);
const kebab = (s) => s.replace(/_/g, '-').replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
const PREFIX = { motion: 'ease', layout: 'layout', radius: 'radius', color: 'color' };

// {color.violet-300} → var(--color-violet-300)
const ref = (v) => String(v).replace(/\{([^}]+)\}/g, (_, p) => {
  const [g, ...rest] = p.split('.');
  return `var(--${PREFIX[g] ?? g}-${kebab(rest.join('-'))})`;
});

const flat = (obj, path = []) =>
  Object.entries(obj).flatMap(([k, t]) =>
    t && typeof t === 'object' && !('$value' in t) ? flat(t, [...path, k]) : [[[...path, k].map(kebab).join('-'), val(t)]]);

const root = [];
for (const [group, tokens] of Object.entries(src)) {
  if (SKIP.has(group)) continue;
  for (const [name, v] of flat(tokens)) root.push(`  --${PREFIX[group] ?? kebab(group)}-${name}: ${ref(v)};`);
}

const themes = Object.fromEntries(Object.entries(src.semantic ?? {}).map(([theme, roles]) =>
  [theme, Object.entries(roles).map(([r, v]) => `  --${kebab(r)}: ${ref(val(v))};`).join('\n')]));
const [first] = Object.keys(themes);
const other = Object.keys(themes).find((t) => t !== first);

let css = `/* Generated by packages/tokens/build.mjs. Do not edit. */\n:root {\n${root.join('\n')}\n}\n`;
for (const [t, body] of Object.entries(themes)) css += `\n${t === first ? ':root, ' : ''}[data-theme='${t}'] {\n  color-scheme: ${t};\n${body}\n}\n`;
if (other) css += `\n@media (prefers-color-scheme: ${other}) {\n  [data-theme='auto'] {\n    color-scheme: ${other};\n${themes[other].replace(/^/gm, '  ')}\n  }\n}\n`;

const fonts = Object.fromEntries(Object.entries(src.font ?? {}).map(([role, f]) =>
  [role, { family: val(f), weights: val(src.fontWeight?.[role]) ?? [400] }]));
const motion = Object.fromEntries(Object.entries(src.motion ?? {}).map(([k, v]) => [k, val(v)]));

mkdirSync(new URL('./dist/', import.meta.url), { recursive: true });
writeFileSync(new URL('./dist/tokens.css', import.meta.url), css);
writeFileSync(new URL('./dist/tokens.json', import.meta.url), JSON.stringify({ fonts, motion, themes: Object.keys(themes), headingWeight: val(src.layout?.heading_weight) ?? 400, mark: src.mark ?? null }, null, 2));
console.log(`tokens: ${root.length} vars, themes: ${Object.keys(themes).join(', ') || 'none'}, fonts: ${Object.keys(fonts).join(', ')}`);
